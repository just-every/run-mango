import {expect,test} from '@playwright/test';
import {signInAsLocalOperator,expectDocumentToFit,expectNoSeriousAxeViolations} from './browser-checks';
import {openPage,hydrated} from '../support/navigation';
import {expectCampaignAxe} from './campaign-axe';

test('[BASE-ACCESS-002][MOBILE-001] phone visitors reach public docs and operators navigate the desk, save a draft and inspect their audience',async({page,request},info)=>{
  test.setTimeout(180000);
  await page.setViewportSize({width:390,height:844});
  const audit=async(name:string)=>{
    await expect(page.locator('main h1').first()).toBeVisible();
    await expectDocumentToFit(page,390);
    if(await page.locator('iframe[title="Saved email preview"]').count())await expectCampaignAxe(page,name);
    else await expectNoSeriousAxeViolations(page,name);
    expect(await page.evaluate(()=>window.__rerHydration?.count??0)).toBe(0);
    await page.screenshot({path:info.outputPath(name+'-390.png'),fullPage:true});
  };
  await openPage(page,'/docs/getting-started');
  const contents=page.getByRole('navigation',{name:'Documentation'}).locator('summary').filter({visible:true});
  await expect(contents).toBeVisible();await contents.focus();await contents.press('Enter');
  await expect(page.locator('details[open] [aria-current="page"]')).toHaveCount(1);
  await audit('public-docs');
  const command=page.locator('.docs-prose pre').first();
  await expect(command).toBeVisible();
  expect(await command.evaluate(node=>node.scrollWidth<=node.clientWidth)).toBe(true);
  expect((await request.get('/app',{maxRedirects:0})).status()).toBe(303);
  await signInAsLocalOperator(page,request);
  await openPage(page,'/app');
  const navigate=async(label:string)=>{
    const menu=page.getByRole('button',{name:/^Menu/});
    await menu.focus();await menu.press('Enter');
    await expect(menu).toHaveAttribute('aria-expanded','true');
    await page.getByRole('navigation',{name:'Operator navigation'}).getByRole('link',{name:label,exact:true}).click();
    await expect(page.locator('main h1').first()).toBeVisible();
    await hydrated(page);
  };
  await navigate('Campaigns');await audit('campaigns');
  await page.getByRole('button',{name:'New campaign',exact:true}).click();
  await page.getByRole('button',{name:'Blank newsletter',exact:true}).click();
  await expect(page.locator('#campaign-composer')).toBeVisible();
  await hydrated(page);
  await page.getByLabel('Campaign name',{exact:true}).fill('Phone garden draft');
  await page.getByLabel('Email subject',{exact:true}).fill('Garden notes from a phone');
  const saved=page.waitForResponse(response=>response.request().method()==='PATCH'&&response.url().includes('/api/campaign-revisions/'));
  await page.getByRole('button',{name:'Save full draft',exact:true}).click();
  expect((await saved).status()).toBe(200);
  await page.reload();
  await expect(page.getByLabel('Campaign name',{exact:true})).toHaveValue('Phone garden draft');
  await expect(page.getByLabel('Email subject',{exact:true})).toHaveValue('Garden notes from a phone');
  await audit('saved-draft');
  await navigate('Audience');await audit('audience');
  await navigate('Insights');await audit('insights');
});
