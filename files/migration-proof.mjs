import {readFile,readdir} from 'node:fs/promises';
import {DatabaseSync} from 'node:sqlite';
import {createHash} from 'node:crypto';
const file='0104_sending_event_silence.sql';
const sql=await readFile('migrations/core/'+file,'utf8');
const db=new DatabaseSync(':memory:');
const files=(await readdir('migrations/core')).filter(name=>name.endsWith('.sql')).sort();
for (const name of files.filter(name=>name<file)) db.exec(await readFile('migrations/core/'+name,'utf8'));
const columns=()=>db.prepare('PRAGMA table_info(recipient_steps)').all().map(row=>row.name);
if(columns().includes('sending_generation'))throw new Error('pre-upgrade schema already changed');
const before=db.prepare('SELECT count(*) AS n FROM recipient_steps').get().n;
db.exec(sql);
for (const name of ['sending_generation','sending_accepted_at','sending_signed_event_at'])if(!columns().includes(name))throw new Error('missing additive provenance '+name);
if(db.prepare('SELECT count(*) AS n FROM recipient_steps').get().n!==before)throw new Error('migration changed existing recipients');
const spec=JSON.parse(await readFile('management/integration/deployment-spec.json','utf8'));
const entry=spec.migrations.find(row=>row.name==='core-'+file);
if(!entry)throw new Error('migration absent from deployment metadata');
const digest=createHash('sha256').update(sql).digest('hex');
if(entry.sha256!==digest||entry.sql!==sql)throw new Error('deployment ledger hash or SQL differs');
console.log(JSON.stringify({file,appliedPriorMigrations:files.filter(name=>name<file).length,sha256:digest,metadataMatches:true,additiveProvenance:true,recipientCountUnchanged:true}));
db.close();
