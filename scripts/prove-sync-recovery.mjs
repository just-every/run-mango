import { evidenceDirectory } from '../tests/support/artifacts.mjs';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const output = evidenceDirectory('sync-recovery');
await mkdir(output, {recursive:true});
const access = new URL((await readFile('.seed/review-access', 'utf8')).trim());
const scenario = `synthetic-review-sync-${Date.now()}`;
access.searchParams.set('scenario', scenario);
const browser = await chromium.launch({headless: true});
const errors = [], external = [];
let page;
const control = (path) => {const url = new URL(path, access.origin); url.searchParams.set('access', access.searchParams.get('access')); return url.href};
try {
  page = await browser.newPage({viewport: {width: 1440, height: 1050}});
  page.on('pageerror', error => errors.push(String(error)));
  await page.route('**/*', route => {
    if (new URL(route.request().url()).hostname === '127.0.0.1') return route.continue();
    external.push(route.request().url()); return route.abort();
  });
  expect((await page.request.post(`${access.origin}/api/store/sync`, {data: {sourceType: 'customer'}})).status()).toBe(401);
  await page.goto(access.href);
  expect((await page.request.post(`${access.origin}/api/store/sync`, {data: {sourceType: 'unknown'}})).status()).toBe(400);
  expect((await page.request.post(`${access.origin}/api/store/sync`, {data: {sourceType: 'order'}})).status()).toBe(409);
  const status = async () => (await page.request.get(`${access.origin}/api/store`)).json();
  await page.request.post(control('/_review/sync-fault'), {data: {failSecond: false}});
  const prior = (await status()).syncRuns.find(run => run.sourceType === 'customer');
  if (prior && ['failed', 'queued', 'running'].includes(prior.state)) {
    await page.request.post(`${access.origin}/api/store/sync`, {data: {sourceType: 'customer', runId: prior.id}});
    await expect.poll(async () => (await status()).syncRuns.find(run => run.id === prior.id)?.state).toBe('completed');
  }
  const before = await status();
  const priorFreshness = before.sourceSyncs.find(source => source.sourceType === 'customer').lastSuccessfulAt;
  expect((await page.request.post(control('/_review/sync-fault'), {data: {failSecond: true}})).status()).toBe(200);
  await page.goto(`${access.origin}/app/store`);
  const customer = page.getByRole('article', {name: 'Customer sync', exact: true});
  await expect(customer.getByRole('button', {name: 'Sync now', exact: true})).toBeVisible();
  const queued = page.waitForResponse(response => response.url().endsWith('/api/store/sync') && response.request().method() === 'POST');
  await customer.getByRole('button', {name: 'Sync now', exact: true}).click();
  const accepted = await queued;
  expect(accepted.status()).toBe(202);
  const runId = (await accepted.json()).runId;
  await expect.poll(async () => (await status()).syncRuns.find(run => run.id === runId)?.state).toBe('failed');
  await page.getByRole('button', {name: 'Refresh sync status'}).click();
  await expect(customer).toContainText('1 pages saved');
  await expect(customer).toContainText('Synthetic second page unavailable');
  const failed = await status();
  expect(failed.sourceSyncs.find(source => source.sourceType === 'customer').lastSuccessfulAt).toBe(priorFreshness);
  expect(JSON.stringify(failed.syncRuns)).not.toContain('nextCursor');
  expect(JSON.stringify(failed.syncRuns)).not.toContain('leaseToken');
  const blocked = await page.request.post(`${access.origin}/api/campaigns/${scenario}/approve`, {data: {revisionId: `${scenario}-v1`, idempotencyKey: `${scenario}-blocked`}});
  expect(blocked.status()).toBe(409);
  const blockBody = await blocked.json();
  expect(blockBody.blockers).toEqual(expect.arrayContaining([expect.objectContaining({kind: 'audience.resolution', status: 'blocked', detail: 'Synthetic second page unavailable. Saved progress is retained; resume after recovery.'})]));
  await page.screenshot({path: join(output, 'sync-failed.png'), fullPage: true});
  const callsBeforeResume = await (await page.request.get(control('/_review/sync-calls'))).json();
  await page.request.post(control('/_review/sync-fault'), {data: {failSecond: false}});
  await customer.getByRole('button', {name: 'Resume sync', exact: true}).click();
  await expect.poll(async () => (await status()).syncRuns.find(run => run.id === runId)?.state).toBe('completed');
  const completed = await status();
  const run = completed.syncRuns.find(run => run.id === runId);
  expect(run).toMatchObject({state: 'completed', pages: 2, records: 3, lastError: null});
  expect(completed.sourceSyncs.find(source => source.sourceType === 'customer').lastError).toBeNull();
  const callsAfterResume = await (await page.request.get(control('/_review/sync-calls'))).json();
  expect(callsAfterResume.filter(call => call.id > callsBeforeResume[0].id).map(call => call.cursor)).toEqual(['second-page']);
  await page.reload();
  await expect(customer).toContainText('2 pages saved');
  await expect(customer).toContainText('completed');
  await page.screenshot({path: join(output, 'sync-completed.png'), fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(391);
  await page.screenshot({path: join(output, 'sync-mobile.png'), fullPage: true});
  await page.goto(`${access.origin}/app/campaigns/${scenario}/review`);
  await expect(page.getByRole('button', {name: 'Approve & schedule', exact: true})).toBeVisible();
  expect(external).toEqual([]); expect(errors).toEqual([]);
  const evidence = {scenario, runId, queued: accepted.status(), failedPages: 1, resumedCursors: ['second-page'], completed: run, staleApprovalStatus: blocked.status(), noExternalRequests: external.length === 0, browserErrors: errors};
  await writeFile(join(output, 'sync-recovery.json'), JSON.stringify(evidence, null, 2) + '\n');
  console.log(JSON.stringify(evidence, null, 2));
} finally {
  if (page) await page.request.post(control('/_review/sync-fault'), {data: {failSecond: false}}).catch(() => {});
  await browser.close();
}
