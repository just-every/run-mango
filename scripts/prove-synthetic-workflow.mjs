import { evidenceDirectory } from '../tests/support/artifacts.mjs';
import { join } from 'node:path';
import { chromium, expect } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const output = evidenceDirectory('synthetic-workflow');
await mkdir(output, {recursive:true});
const access = new URL((await readFile('.seed/review-access', 'utf8')).trim());
const scenario = `synthetic-review-browser-${Date.now()}`;
access.searchParams.set('scenario', scenario);
const browser = await chromium.launch({headless: true});
const errors = [];
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1050}});
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', message => {if (message.type() === 'error') errors.push(message.text())});
  await page.goto(access.href);
  const name = `Synthetic recovery ${scenario}`;
  await page.getByLabel('Campaign name', {exact: true}).fill(name);
  const savedResponse = page.waitForResponse(response => response.request().method() === 'PATCH');
  await page.getByRole('button', {name: 'Save full draft', exact: true}).click();
  const saved = await savedResponse;
  expect(saved.status(), await saved.text()).toBe(200);
  await expect(page.getByRole('status')).toContainText('Draft saved.');
  await page.reload();
  await expect(page.getByLabel('Campaign name', {exact: true})).toHaveValue(name);
  await page.getByRole('button', {name: 'Approve & schedule', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('approved and scheduled');
  await page.getByRole('link', {name: 'View schedule & cancellation', exact: true}).click();
  await expect(page.getByRole('button', {name: 'Cancel campaign', exact: true})).toBeVisible();
  await page.reload();
  await page.getByRole('button', {name: 'Cancel campaign', exact: true}).click();
  await page.getByRole('button', {name: 'Confirm cancellation', exact: true}).click();
  await expect(page.getByRole('status')).toContainText('Campaign cancelled.');
  await expect(page.getByRole('button', {name: 'Cancel campaign', exact: true})).toHaveCount(0);
  await page.reload();
  const response = await page.request.get(new URL(`/api/campaigns/${scenario}`, access.origin).href);
  expect(response.status()).toBe(200);
  const detail = await response.json();
  expect(detail.campaign.state).toBe('cancelled');
  expect(detail.revision.name).toBe(name);
  expect(detail.audience.eligibleCount).toBe(1);
  expect(errors).toEqual([]);
  await page.screenshot({path: join(output, 'synthetic-cancelled.png'), fullPage: true});
  await writeFile(join(output, 'synthetic-workflow.json'), JSON.stringify({scenario, savedDraftRecoveredAfterReload: true, approvalRecoveredAfterReload: true, cancellationRecoveredAfterReload: true, campaignState: detail.campaign.state, eligibleCount: detail.audience.eligibleCount, errors, providers: 'task-owned synthetic; sends disabled'}, null, 2));
  console.log(JSON.stringify({scenario, state: detail.campaign.state, errors}));
} finally { await browser.close(); }
